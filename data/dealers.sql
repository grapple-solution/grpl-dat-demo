-- Dealers of the demo, for the "dealers" drilldown (Country -> City -> Dealer).
-- Independent of datecode2: own tables, with brand_hst holding a real HST code
-- (manufacturer) of datecode2. Edge cases for the "None" entry: 5 online-only
-- dealers have no city (but a country), and 2 cities have no country.
-- INSERT IGNORE keeps a second run, or a run after a partial one, harmless.
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS country (
  id INT NOT NULL,
  name VARCHAR(128) NOT NULL,
  PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS city (
  id INT NOT NULL,
  name VARCHAR(128) NOT NULL,
  country_id INT NULL,
  PRIMARY KEY (id),
  KEY idx_city_country_name (country_id, name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS dealer (
  id INT NOT NULL,
  name VARCHAR(255) NOT NULL,
  city_id INT NULL,
  country_id INT NULL,
  brand_hst DECIMAL(10,0) NULL,
  -- copies of the city and country names, so the dealer table can show them
  -- next to the ids; filled from city/country at the end of this file
  city_name VARCHAR(128) NULL,
  country_name VARCHAR(128) NULL,
  PRIMARY KEY (id),
  KEY idx_dealer_city_name (city_id, name),
  KEY idx_dealer_country (country_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

